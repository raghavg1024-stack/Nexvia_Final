"use server";

import { createClient } from "@/lib/supabase/server";

export interface Notification {
  id: string;
  user_id: string;
  type: "application_status" | "streak_reminder" | "weekly_recap" | "system";
  title: string;
  message: string;
  data: Record<string, unknown> | null;
  read: boolean;
  created_at: string;
}

export async function getNotifications(limit = 20, unreadOnly = false): Promise<Notification[]> {
  const supabase = await createClient();
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return [];

  let query = supabase
    .from("notifications")
    .select("*")
    .eq("user_id", user.id)
    .order("created_at", { ascending: false })
    .limit(limit);

  if (unreadOnly) {
    query = query.eq("read", false);
  }

  const { data } = await query;
  return data || [];
}

export async function markNotificationRead(notificationId: string): Promise<{ ok: boolean } | { error: string }> {
  const supabase = await createClient();
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return { error: "Not authenticated" };

  const { error } = await supabase
    .from("notifications")
    .update({ read: true })
    .eq("id", notificationId)
    .eq("user_id", user.id);

  if (error) return { error: error.message };
  return { ok: true };
}

